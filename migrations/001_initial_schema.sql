-- ============================================================
-- EQUIPMENT TABLES
-- Users define their own grinders and brewers
-- ============================================================

CREATE TABLE grinders (
    id          SERIAL PRIMARY KEY,
    name        TEXT NOT NULL,           -- e.g. "ZP6 Special"
    notes       TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE brewers (
    id          SERIAL PRIMARY KEY,
    name        TEXT NOT NULL,           -- e.g. "Hario Glass V60"
    brew_method TEXT NOT NULL,           -- 'filter' | 'espresso' | 'immersion' | 'other'
    brew_type   TEXT,                    -- 'v60' | 'chemex' | 'aeropress' | 'espresso' | etc
    brand       TEXT,
    model       TEXT,
    notes       TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ============================================================
-- COFFEE BAGS
-- One row = one physical bag of coffee
-- ============================================================

CREATE TABLE coffee_bags (
    id                      SERIAL PRIMARY KEY,

    -- Human-friendly hash: e.g. "MCR-0042" (auto-generated by app logic)
    bag_hash                TEXT UNIQUE,

    -- Roaster info
    roaster                 TEXT,      -- "Morgon Coffee Roasters"
    roaster_origin_city     TEXT,      -- "Gothenburg"
    roaster_origin_country  TEXT,      -- "Sweden"

    -- Bean info
    origin_country          TEXT,      -- "Ethiopia"
    origin_region           TEXT,      -- "Yirgacheffe"
    variety                 TEXT,      -- "Heirloom", "Gesha", "Typica"
    process                 TEXT,      -- "Washed", "Natural", "Honey"
    taste_notes             TEXT[],    -- array: ["blueberry", "dark chocolate"]
    bean_type               TEXT,      -- "Heirloom", "SL28", etc (maps to "type" in spec)

    -- Dates
    harvest_date            DATE,
    roast_date              DATE,

    -- Advanced / optional
    caffeine_free           BOOLEAN NOT NULL DEFAULT false,
    batch_id                TEXT,                   -- roaster's own batch number
    image_path              TEXT,                   -- path to photo on server

    created_at              TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ============================================================
-- BREWS
-- One row = one brew session
-- ============================================================

CREATE TABLE brews (
    id              SERIAL PRIMARY KEY,

    -- e.g. "MCR-0042-B003" - generated by app from bag_hash + per-bag counter
    brew_hash       TEXT UNIQUE,

    coffee_bag_id   INT REFERENCES coffee_bags(id) ON DELETE SET NULL,

    -- When
    brew_datetime   TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- Equipment
    grinder_id      INT REFERENCES grinders(id) ON DELETE SET NULL,
    grind_setting   TEXT,               -- "4.5" - text because settings vary by grinder
    brewer_id       INT REFERENCES brewers(id) ON DELETE SET NULL,
    filter_paper    TEXT,               -- "Cafec Abaca"

    -- Measurements (store canonical values; conversions done in app)
    coffee_grams    NUMERIC(6,1),       -- e.g. 15.0
    water_grams     NUMERIC(7,1),       -- e.g. 250.0
    -- ratio is DERIVED: coffee_grams / water_grams — NOT stored to avoid staleness
    water_temp_c    NUMERIC(5,1),       -- always store Celsius; convert in UI
    brew_time_secs  INT,                -- store as seconds; display as mm:ss in UI

    -- Brew steps: either free text or structured array
    -- Structured example:
    -- [{"name":"Bloom","duration_secs":45,"water_ml":50,"notes":"Swirl gently"},
    --  {"name":"Pour 1","duration_secs":30,"water_ml":100,"notes":""}]
    brew_steps      JSONB,

    -- Review
    rating          TEXT CHECK (rating IN ('excellent','good','ok','so-so','bad')),
    review          TEXT,               -- free text review
    notes           TEXT,               -- general notes

    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ============================================================
-- INDEXES for common query patterns
-- ============================================================

CREATE INDEX idx_brews_coffee_bag    ON brews(coffee_bag_id);
CREATE INDEX idx_brews_datetime      ON brews(brew_datetime DESC);
CREATE INDEX idx_brews_rating        ON brews(rating);
CREATE INDEX idx_coffee_bags_roaster ON coffee_bags(roaster);
CREATE INDEX idx_coffee_bags_origin  ON coffee_bags(origin_country, origin_region);

